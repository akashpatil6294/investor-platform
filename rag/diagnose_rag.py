"""
Diagnostic for the RAG pipeline.
Run this to inspect what's actually stored in Supabase
and what each query retrieves.
"""

import os
from dotenv import load_dotenv
from sentence_transformers import SentenceTransformer

from vectorstore.supabase_vectorstore import (
    SupabaseVectorStore,
    Retriever,
)

load_dotenv()

EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"


# ------------------------------------------------------------
# Adapter (same as your main file)
# ------------------------------------------------------------

class SentenceTransformerEmbeddings:

    def __init__(self, model):
        self.model = model

    def embed_query(self, text: str) -> list[float]:
        vector = self.model.encode(
            text,
            normalize_embeddings=True,
        )
        return vector.tolist()


def hr(title=""):
    print()
    print("=" * 80)
    if title:
        print(title)
        print("=" * 80)


def main():

    hr("LOADING EMBEDDING MODEL")
    model = SentenceTransformer(EMBEDDING_MODEL)
    print("Loaded.")

    embeddings = SentenceTransformerEmbeddings(model)

    hr("CONNECTING TO SUPABASE")
    vector_store = SupabaseVectorStore()
    print("Connected.")

    retriever = Retriever(
        vector_store=vector_store,
        embeddings=embeddings,
    )
    print("Retriever ready.")

    # ========================================================
    # STEP 1: Inspect what's in the vector store
    # ========================================================
    #
    # We try a very generic query to grab a broad sample
    # of chunks. This tells us what the store actually
    # contains.
    # ========================================================

    hr("STEP 1 — WHAT'S IN THE STORE?")

    broad_queries = [
        "Apple 2024 Form 10-K",
        "Consolidated Statements of Operations",
        "Consolidated Balance Sheets",
        "Consolidated Statements of Cash Flows",
        "Total assets total liabilities",
        "Net income per share",
        "Risk factors competition",
    ]

    for q in broad_queries:

        print()
        print(f"QUERY: {q!r}")

        try:
            results = retriever.retrieve(query=q, k=5)
        except Exception as error:
            print(f"  ERROR: {error}")
            continue

        if not results:
            print("  No results returned.")
            continue

        for i, r in enumerate(results, start=1):
            sim = r.get("similarity", 0)
            meta = r.get("metadata", {})
            content = r.get("content", "")

            try:
                sim_str = f"{float(sim):.4f}"
            except (TypeError, ValueError):
                sim_str = str(sim)

            preview = content[:200].replace("\n", " ")
            print(
                f"  [{i}] sim={sim_str} meta={meta}\n"
                f"      {preview}..."
            )

    # ========================================================
    # STEP 2: Search specifically for the financial figures
    # ========================================================
    #
    # If any of these return a chunk with a dollar figure,
    # we know the data exists.
    # ========================================================

    hr("STEP 2 — SEARCH FOR SPECIFIC FIGURES")

    figure_queries = [
        "Total net sales 391,035",
        "Net income 93,736",
        "Operating income 123,216",
        "Cash generated by operating activities 118,254",
        "Total assets 364,980",
        "Total liabilities 308,030",
        "391,035",
        "93,736",
        "364,980",
        "308,030",
        "Cash flows from operating activities",
        "Total shareholders equity",
    ]

    for q in figure_queries:

        print()
        print(f"QUERY: {q!r}")

        try:
            results = retriever.retrieve(query=q, k=3)
        except Exception as error:
            print(f"  ERROR: {error}")
            continue

        if not results:
            print("  No results.")
            continue

        for i, r in enumerate(results, start=1):
            sim = r.get("similarity", 0)
            meta = r.get("metadata", {})
            content = r.get("content", "")

            try:
                sim_str = f"{float(sim):.4f}"
            except (TypeError, ValueError):
                sim_str = str(sim)

            preview = content[:250].replace("\n", " ")
            print(
                f"  [{i}] sim={sim_str} meta={meta}\n"
                f"      {preview}..."
            )

    # ========================================================
    # STEP 3: Dump every source/chunk_index present
    # ========================================================
    #
    # If the store only has a handful of chunks, ingestion
    # is the problem, not retrieval.
    # ========================================================

    hr("STEP 3 — SAMPLE DUMP OF STORED CHUNKS")

    # Try to find any method that lists chunks.
    # We probe a few common method names defensively.

    for method_name in [
        "list_chunks",
        "get_all",
        "fetch_all",
        "all_documents",
    ]:

        method = getattr(vector_store, method_name, None)

        if method is None:
            continue

        print(f"Trying vector_store.{method_name}()...")

        try:
            data = method()

            print(f"  Returned {len(data)} items.")

            for i, row in enumerate(data[:30], start=1):
                meta = row.get("metadata", {}) if isinstance(row, dict) else {}
                content = row.get("content", "") if isinstance(row, dict) else str(row)
                print(f"  [{i}] meta={meta}")
                print(f"      {content[:150]!r}")

            break

        except Exception as error:
            print(f"  {method_name} failed: {error}")

    else:
        print(
            "No bulk-list method found on vector store. "
            "Skipping raw dump."
        )

    hr("DIAGNOSTIC COMPLETE")


if __name__ == "__main__":
    main()