"""Locate the primary financial statements inside a report's markdown.

Works on headings from any jurisdiction — IFRS/Ind AS ("Statement of profit
and loss", "Balance sheet", "Cash flow statement"), US GAAP ("Consolidated
Statements of Operations", "Consolidated Balance Sheets", "Consolidated
Statements of Cash Flows"), and common synonyms — plus XBRL section codes
seen in regulatory filings (e.g. MCA AOC-4 "[210000] Statement of profit and
loss"). No company-specific knowledge.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from ingestion.pdf_to_markdown import split_markdown_pages

STATEMENT_KINDS = ("income", "balance", "cashflow")

# Ordered synonym lists; regexes are case-insensitive.
HEADING_SYNONYMS = {
    "income": [
        r"statement\s+of\s+profit\s+and\s+loss",
        r"statements?\s+of\s+operations",
        r"income\s+statement",
        r"compte\s+de\s+r[ée]sultat", r"estado\s+de\s+resultados", r"gewinn.und.verlustrechnung",
        r"profit\s+and\s+loss\s+account",
        r"consolidated\s+income\s+statement",
        r"statement\s+of\s+comprehensive\s+income",
    ],
    "balance": [
        r"balance\s+sheets?", r"bilan", r"bilanz", r"estado\s+de\s+situaci[óo]n\s+financiera",
        r"statement\s+of\s+financial\s+position",
        r"statement\s+of\s+assets\s+and\s+liabilities",
    ],
    "cashflow": [
        r"cash\s+flow\s+statements?", r"tableau\s+des\s+flux\s+de\s+tr[ée]sorerie", r"estado\s+de\s+flujos\s+de\s+efectivo", r"kapitalflussrechnung",
        r"statements?\s+of\s+cash\s+flows?",
        r"statement\s+of\s+cash\s+flow",
        r"cash\s+flow\s+statement,?\s+indirect",
    ],
}

# Row-label evidence that a page carries the numbers we need.
ROW_LABEL_SYNONYMS = {
    "income": [
        "revenue from operations", "total income", "revenue", "net sales",
        "total revenues", "cost of materials", "total expenses",
        "profit before tax", "profit for the year", "net income",
        "profit/(loss) for the year", "earnings per share", "other income",
    ],
    "balance": [
        "total assets", "total liabilities", "total equity",
        "total equity and liabilities", "shareholders' equity",
        "stockholders' equity", "total current assets",
        "total non-current assets", "total current liabilities",
        "trade receivables", "property, plant and equipment",
    ],
    "cashflow": [
        "net cash flows from", "operating activities", "investing activities",
        "financing activities", "cash generated by operating",
        "cash provided by operating", "net cash from operations",
        "profit before tax", "depreciation",
    ],
}

HEADING_RE_CACHE: dict[str, re.Pattern] = {}


def _heading_regex(kind: str) -> re.Pattern:
    if kind not in HEADING_RE_CACHE:
        joined = "|".join(f"(?:{p})" for p in HEADING_SYNONYMS[kind])
        HEADING_RE_CACHE[kind] = re.compile(joined, re.IGNORECASE)
    return HEADING_RE_CACHE[kind]


@dataclass
class StatementLocation:
    kind: str
    pages: list[tuple[int, str]] = field(default_factory=list)

    @property
    def page_numbers(self) -> list[int]:
        return [number for number, _ in self.pages]

    @property
    def text(self) -> str:
        return "\n\n".join(f"<!-- PAGE:{number} -->\n{text}" for number, text in self.pages)


def score_page(kind: str, text: str) -> int:
    """Higher score = more likely this page belongs to the statement."""
    score = 0
    lowered = text.lower()
    heading = _heading_regex(kind)
    # Heading matches weighted by how early/short the match is.
    if heading.search(text):
        score += 6
        # A short heading-like line ("## Balance sheet") is a stronger signal.
        for line in text.splitlines():
            line_s = line.strip().lstrip("#*|").strip()
            if line_s and heading.fullmatch(line_s):
                score += 4
                break
    hits = sum(1 for label in ROW_LABEL_SYNONYMS[kind] if label in lowered)
    score += min(hits, 8)
    # Statement pages are table-heavy.
    score += min(text.count("|") // 20, 3)
    return score


def locate_statement_pages(
    pages: list[tuple[int, str]],
    max_pages_per_statement: int = 6,
    basis: str | None = None,
) -> dict[str, StatementLocation]:
    """Pick the pages of each primary statement from page-split markdown."""
    # Carry explicit statement basis forward, including continuation pages.
    scoped = []
    active = None
    for number, content in pages:
        heading = content[:1000].lower()
        if "consolidated" in heading:
            active = "consolidated"
        elif "standalone" in heading:
            active = "standalone"
        scoped.append((number, content, active))
    chosen_basis = basis or ("consolidated" if any(b == "consolidated" for _, _, b in scoped) else None)
    selected = [(n, t) for n, t, b in scoped if b is None or chosen_basis is None or b == chosen_basis]
    pages = selected
    result: dict[str, StatementLocation] = {}
    for kind in STATEMENT_KINDS:
        scored = sorted(
            ((score_page(kind, text), number, text) for number, text in pages),
            key=lambda item: item[0],
            reverse=True,
        )
        best = [item for item in scored if item[0] >= 4][:max_pages_per_statement]
        best.sort(key=lambda item: item[1])
        result[kind] = StatementLocation(
            kind=kind,
            pages=[(number, text) for _, number, text in best],
        )
    return result


def load_report_pages(source_file: str) -> list[tuple[int, str]] | None:
    """Load page-split markdown for a stored report; None when absent."""
    from pathlib import Path

    from services.reports import ROOT

    if not source_name_ok(source_file):
        return None
    path = ROOT / "data" / "markdown" / source_file
    if not path.is_file():
        return None
    try:
        markdown = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return None
    return split_markdown_pages(markdown)


def source_name_ok(name: str) -> bool:
    """Only plain filenames inside the markdown directory are readable."""
    from pathlib import PurePath

    if not name or PurePath(name).name != name:
        return False
    return "/" not in name and "\\" not in name and name.endswith(".md")
