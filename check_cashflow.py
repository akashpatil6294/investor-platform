import os
from dotenv import load_dotenv
from supabase import create_client

load_dotenv()
c = create_client(
    os.getenv("SUPABASE_URL"),
    os.getenv("SUPABASE_SECRET_KEY"),
)

for company in ["Amazon", "Microsoft", "Tesla"]:
    rows = c.table("documents").select(
        "metadata,content"
    ).eq("company", company).execute().data

    print(f"\n{'=' * 60}")
    print(f"{company}: {len(rows)} chunks")
    print("=" * 60)

    hits = 0
    for r in rows:
        content = r.get("content", "")
        lower = content.lower()
        if (
            "cash generated by operating" in lower
            or "cash provided by operating" in lower
            or "cash flows from operating" in lower
        ):
            idx = (r.get("metadata") or {}).get("chunk_index")
            hits += 1
            print(f"\n  [{idx}] full content:")
            print(f"  {content[:1500]!r}")
            if hits >= 3:
                break

    if hits == 0:
        print("  No cash-flow chunks found.")